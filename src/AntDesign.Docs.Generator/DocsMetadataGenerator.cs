using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.Json;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace AntDesign.Docs.Generator;

[Generator]
public sealed class DocsMetadataGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor InvalidMetadata = new(
        "ADBDOCSGEN001",
        "Invalid docs metadata",
        "Could not generate docs metadata from '{0}': {1}",
        "Docs metadata",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var markdownPaths = context.AdditionalTextsProvider
            .Select(static (file, _) => file.Path.Replace('\\', '/'))
            .Where(static path => path.Contains("Demos/Components/") &&
                (path.EndsWith("/doc/index.en-US.md", StringComparison.Ordinal) ||
                 path.EndsWith("/doc/index.zh-CN.md", StringComparison.Ordinal)))
            .Collect();

        context.RegisterSourceOutput(markdownPaths, static (productionContext, paths) =>
        {
            var keys = paths.Select(path => path.Substring(path.LastIndexOf("Demos/Components/", StringComparison.Ordinal) + "Demos/Components/".Length)
                    .Replace("/doc/index.", "/"))
                .Select(path => path.Substring(0, path.Length - ".md".Length))
                .Distinct(StringComparer.Ordinal).OrderBy(path => path, StringComparer.Ordinal);
            var literals = string.Join(",\n        ", keys.Select(path => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(path, true)));
            productionContext.AddSource("GeneratedComponentMarkdown.g.cs", SourceText.From(
                "// <auto-generated />\nnamespace AntDesign.Docs.Services;\n" +
                "internal static class GeneratedComponentMarkdown\n{\n" +
                "    private static readonly System.Collections.Generic.HashSet<string> Paths = new(System.StringComparer.Ordinal)\n    {\n        " +
                literals + "\n    };\n" +
                "    internal static bool HasDocument(string component, string language) => Paths.Contains(component + \"/\" + language);\n}\n", Encoding.UTF8));
        });

        var metadataFiles = context.AdditionalTextsProvider
            .Where(static file => IsDocsMetadata(Path.GetFileName(file.Path)))
            .Select(static (file, cancellationToken) => new MetadataFile(
                Path.GetFileName(file.Path),
                file.Path,
                file.GetText(cancellationToken)?.ToString()))
            .Collect();

        context.RegisterSourceOutput(metadataFiles, static (productionContext, files) =>
        {
            try
            {
                var metadata = files
                    .Where(file => !string.IsNullOrWhiteSpace(file.Text))
                    .Select(file => new ParsedMetadata(file, JsonDocument.Parse(file.Text!)))
                    .ToArray();
                var source = Generate(metadata);
                productionContext.AddSource("GeneratedDocsMetadata.g.cs", SourceText.From(source, Encoding.UTF8));
            }
            catch (Exception exception)
            {
                productionContext.ReportDiagnostic(Diagnostic.Create(InvalidMetadata, Location.None, "wwwroot/meta/*.json", exception.Message));
            }
        });
    }

    private static bool IsDocsMetadata(string name) =>
        (name.StartsWith("components.", StringComparison.OrdinalIgnoreCase)
            || name.StartsWith("menu.", StringComparison.OrdinalIgnoreCase)
            || name.StartsWith("demos.", StringComparison.OrdinalIgnoreCase)
            || name.StartsWith("docs.", StringComparison.OrdinalIgnoreCase))
        && name.EndsWith(".json", StringComparison.OrdinalIgnoreCase);

    private static string Generate(ParsedMetadata[] files)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />")
            .AppendLine("#nullable enable")
            .AppendLine("using System;")
            .AppendLine("using System.Collections.Generic;")
            .AppendLine("using System.Linq;")
            .AppendLine("using AntDesign.Docs;")
            .AppendLine()
            .AppendLine("namespace AntDesign.Docs.Services;")
            .AppendLine()
            .AppendLine("internal static class GeneratedDocsMetadata")
            .AppendLine("{");

        foreach (var file in files.OrderBy(file => file.File.Name, StringComparer.Ordinal))
        {
            var (kind, language) = ParseName(file.File.Name);
            if (kind is null || language is null) continue;
            var items = file.Document.RootElement.EnumerateArray().ToArray();
            if (kind == "components")
            {
                var factories = new List<string>();
                for (var index = 0; index < items.Length; index++)
                {
                    var method = $"CreateComponent_{language.Replace('-', '_')}_{index}";
                    factories.Add(method + "()");
                    EmitComponentFactory(builder, method, items[index], language, index);
                }
                EmitLazyArray(builder, FieldName(kind, language), "DemoComponent", factories);
            }
            else
            {
                EmitLazyArray(builder, FieldName(kind, language), "DemoMenuItem", items.Select(item => DemoMenuExpression(item, 2)).ToArray());
            }
        }

        builder.AppendLine()
            .AppendLine("    internal static DemoComponent[] GetComponents(string? language) => NormalizeLanguage(language) switch")
            .AppendLine("    {");
        EmitLanguageSwitch(builder, files, "components");
        builder.AppendLine("        _ => Array.Empty<DemoComponent>(),")
            .AppendLine("    };")
            .AppendLine()
            .AppendLine("    internal static DemoMenuItem[] GetMenu(string? language) => GetMenuData(\"menu\", language);")
            .AppendLine("    internal static DemoMenuItem[] GetDemoMenu(string? language) => GetMenuData(\"demos\", language);")
            .AppendLine("    internal static DemoMenuItem[] GetDocsMenu(string? language) => GetMenuData(\"docs\", language);")
            .AppendLine()
            .AppendLine("    private static DemoMenuItem[] GetMenuData(string kind, string? language)")
            .AppendLine("    {")
            .AppendLine("        var normalizedLanguage = NormalizeLanguage(language);")
            .AppendLine("        return (kind, normalizedLanguage) switch")
            .AppendLine("        {");

        foreach (var file in files.OrderBy(file => file.File.Name, StringComparer.Ordinal))
        {
            var (kind, language) = ParseName(file.File.Name);
            if (kind is null || language is null || kind == "components") continue;
            builder.Append("            (").Append(Literal(kind)).Append(", ").Append(Literal(language)).Append(") => ")
                .Append(FieldName(kind, language)).AppendLine(".Value,");
        }

        builder.AppendLine("            _ => Array.Empty<DemoMenuItem>(),")
            .AppendLine("        };")
            .AppendLine("    }")
            .AppendLine()
            .AppendLine("    internal static DemoComponent? GetComponent(string? language, string key) =>")
            .AppendLine("        GetComponents(language).FirstOrDefault(component => string.Equals(")
            .AppendLine("            $\"{component.Category}/{component.Title}\", key, StringComparison.OrdinalIgnoreCase));")
            .AppendLine()
            .AppendLine("    internal static Type? GetDemoType(string? name) => name switch")
            .AppendLine("    {");

        foreach (var typeName in GetDemoTypes(files).Distinct(StringComparer.Ordinal).OrderBy(name => name, StringComparer.Ordinal))
        {
            var qualifiedName = typeName.StartsWith("AntDesign.Docs.", StringComparison.Ordinal)
                ? typeName
                : "AntDesign.Docs." + typeName;
            builder.Append("        ").Append(Literal(typeName)).Append(" => typeof(")
                .Append("global::").Append(qualifiedName).AppendLine("),");
        }

        builder.AppendLine("        _ => null,")
            .AppendLine("    };")
            .AppendLine()
            .AppendLine("    private static string NormalizeLanguage(string? language) =>")
            .AppendLine("        string.Equals(language, \"zh-CN\", StringComparison.OrdinalIgnoreCase) ? \"zh-CN\" : \"en-US\";")
            .AppendLine("}");
        return builder.ToString();
    }

    private static void EmitLanguageSwitch(StringBuilder builder, ParsedMetadata[] files, string kind)
    {
        foreach (var file in files)
        {
            var (fileKind, language) = ParseName(file.File.Name);
            if (fileKind != kind || language is null) continue;
            builder.Append("        ").Append(Literal(language)).Append(" => ").Append(FieldName(kind, language)).AppendLine(".Value,");
        }
    }

    private static void EmitLazyArray(StringBuilder builder, string field, string itemType, IReadOnlyList<string> items)
    {
        builder.Append("    private static readonly Lazy<").Append(itemType).Append("[]> ").Append(field)
            .Append(" = new(() => new ").Append(itemType).AppendLine("[]")
            .AppendLine("    {");
        foreach (var item in items) builder.Append("        ").Append(item).AppendLine(",");
        builder.AppendLine("    });");
    }

    private static void EmitComponentFactory(StringBuilder builder, string method, JsonElement component, string language, int index)
    {
        var demoMethods = new List<string>();
        var hasDemoList = component.TryGetProperty("DemoList", out var demos) && demos.ValueKind == JsonValueKind.Array;
        if (hasDemoList)
        {
            var demoIndex = 0;
            foreach (var demo in demos.EnumerateArray())
            {
                var demoMethod = $"CreateDemo_{language.Replace('-', '_')}_{index}_{demoIndex++}";
                demoMethods.Add(demoMethod);
                EmitDemoFactory(builder, demoMethod, demo);
            }
        }

        builder.Append("    private static DemoComponent ").Append(method).AppendLine("() => new()")
            .AppendLine("    {");
        EmitStringProperty(builder, component, "Category");
        EmitStringProperty(builder, component, "Title");
        EmitStringProperty(builder, component, "SubTitle");
        EmitStringProperty(builder, component, "Type");
        EmitStringProperty(builder, component, "Desc");
        EmitStringProperty(builder, component, "ApiDoc");
        EmitStringProperty(builder, component, "Faq");
        EmitNumberProperty(builder, component, "Cols", string.Empty);
        EmitStringProperty(builder, component, "Cover");

        if (hasDemoList)
        {
            builder.AppendLine("        DemoList = new List<DemoItem>")
                .AppendLine("        {");
            foreach (var demoMethod in demoMethods) builder.Append("            ").Append(demoMethod).AppendLine("(),");
            builder.AppendLine("        },");
        }
        builder.AppendLine("    };");
    }

    private static void EmitDemoFactory(StringBuilder builder, string method, JsonElement demo)
    {
        builder.Append("    private static DemoItem ").Append(method).AppendLine("() => new()")
            .AppendLine("    {");
        EmitNumberProperty(builder, demo, "Order", "m");
        EmitStringProperty(builder, demo, "Name");
        EmitStringProperty(builder, demo, "Title");
        EmitStringProperty(builder, demo, "Description");
        EmitStringProperty(builder, demo, "Code");
        EmitStringProperty(builder, demo, "Type");
        EmitStringProperty(builder, demo, "Style");
        EmitNumberProperty(builder, demo, "Iframe", string.Empty);
        EmitStringProperty(builder, demo, "Link");
        EmitBooleanProperty(builder, demo, "Docs");
        EmitBooleanProperty(builder, demo, "Debug");
        if (demo.TryGetProperty("AdditionalFiles", out var additional) && additional.ValueKind == JsonValueKind.Object)
        {
            builder.AppendLine("        AdditionalFiles = new Dictionary<string, string>")
                .AppendLine("        {");
            foreach (var entry in additional.EnumerateObject())
            {
                builder.Append("            [").Append(Literal(entry.Name)).Append("] = ")
                    .Append(StringExpression(entry.Value.GetString() ?? string.Empty)).AppendLine(",");
            }
            builder.AppendLine("        },");
        }
        builder.AppendLine("    };");
    }

    private static string DemoMenuExpression(JsonElement item, int indent)
    {
        var padding = new string(' ', indent * 4);
        var builder = new StringBuilder("new DemoMenuItem {\n");
        AppendMenuProperty(builder, padding, "Order", item, "Order", "f");
        AppendMenuProperty(builder, padding, "Title", item, "Title");
        AppendMenuProperty(builder, padding, "SubTitle", item, "SubTitle");
        AppendMenuProperty(builder, padding, "Type", item, "Type");
        AppendMenuProperty(builder, padding, "Url", item, "Url");
        AppendMenuProperty(builder, padding, "Cover", item, "Cover");
        if (item.TryGetProperty("Children", out var children) && children.ValueKind == JsonValueKind.Array)
        {
            builder.Append(padding).Append("Children = new DemoMenuItem[] { ")
                .Append(string.Join(", ", children.EnumerateArray().Select(child => DemoMenuExpression(child, indent + 1))))
                .AppendLine(" },");
        }
        builder.Append(padding.Substring(0, Math.Max(0, padding.Length - 4))).Append('}');
        return builder.ToString();
    }

    private static void AppendMenuProperty(StringBuilder builder, string padding, string targetName, JsonElement source, string sourceName, string numericSuffix = "")
    {
        if (!source.TryGetProperty(sourceName, out var value) || value.ValueKind == JsonValueKind.Null) return;
        var expression = value.ValueKind == JsonValueKind.String
            ? Literal(value.GetString() ?? string.Empty)
            : value.GetRawText() + numericSuffix;
        builder.Append(padding).Append(targetName).Append(" = ").Append(expression).AppendLine(",");
    }

    private static void EmitStringProperty(StringBuilder builder, JsonElement source, string name)
    {
        if (source.TryGetProperty(name, out var value) && value.ValueKind == JsonValueKind.String)
        {
            builder.Append("        ").Append(name).Append(" = ")
                .Append(StringExpression(value.GetString() ?? string.Empty)).AppendLine(",");
        }
    }

    private static void EmitNumberProperty(StringBuilder builder, JsonElement source, string name, string suffix)
    {
        if (source.TryGetProperty(name, out var value) && value.ValueKind == JsonValueKind.Number)
        {
            builder.Append("        ").Append(name).Append(" = ").Append(value.GetRawText()).Append(suffix).AppendLine(",");
        }
    }

    private static void EmitBooleanProperty(StringBuilder builder, JsonElement source, string name)
    {
        if (source.TryGetProperty(name, out var value) && (value.ValueKind == JsonValueKind.True || value.ValueKind == JsonValueKind.False))
        {
            builder.Append("        ").Append(name).Append(" = ").Append(value.GetBoolean() ? "true" : "false").AppendLine(",");
        }
    }

    private static string StringExpression(string value)
    {
        const int chunkSize = 6000;
        if (value.Length <= chunkSize) return Literal(value);
        var chunks = new List<string>();
        for (var offset = 0; offset < value.Length; offset += chunkSize)
        {
            chunks.Add(Literal(value.Substring(offset, Math.Min(chunkSize, value.Length - offset))));
        }
        return "string.Concat(new string[] { " + string.Join(", ", chunks) + " })";
    }

    private static IEnumerable<string> GetDemoTypes(IEnumerable<ParsedMetadata> files)
    {
        foreach (var file in files.Where(file => ParseName(file.File.Name).Kind == "components"))
        {
            if (file.Document.RootElement.ValueKind != JsonValueKind.Array) continue;
            foreach (var component in file.Document.RootElement.EnumerateArray())
            {
                if (!component.TryGetProperty("DemoList", out var demos) || demos.ValueKind != JsonValueKind.Array) continue;
                foreach (var demo in demos.EnumerateArray())
                {
                    if (demo.TryGetProperty("Type", out var type) && type.ValueKind == JsonValueKind.String && !string.IsNullOrWhiteSpace(type.GetString()))
                    {
                        yield return type.GetString()!;
                    }
                }
            }
        }
    }

    private static (string? Kind, string? Language) ParseName(string fileName)
    {
        var parts = fileName.Split('.');
        return parts.Length == 3 ? (parts[0].ToLowerInvariant(), parts[1]) : (null, null);
    }

    private static string FieldName(string kind, string language) =>
        $"{kind}_{language.Replace('-', '_')}";

    private static string Literal(string value) => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, quote: true);

    private sealed class MetadataFile
    {
        internal MetadataFile(string name, string path, string? text) { Name = name; Path = path; Text = text; }
        internal string Name { get; }
        internal string Path { get; }
        internal string? Text { get; }
    }

    private sealed class ParsedMetadata
    {
        internal ParsedMetadata(MetadataFile file, JsonDocument document) { File = file; Document = document; }
        internal MetadataFile File { get; }
        internal JsonDocument Document { get; }
    }
}
