using System;
using System.Collections.Generic;
using System.IO;
using System.IO.Compression;
using System.Linq;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace AntDesign.Docs.Generator;

[Generator]
public sealed class LlmsMarkdownGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor InvalidInput = new("ADBLLMS001", "Invalid LLM input", "Could not generate LLM Markdown: {0}", "Docs", DiagnosticSeverity.Error, true);
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var inputs = context.AdditionalTextsProvider.Where(file => {
            var name = Path.GetFileName(file.Path);
            return name.StartsWith("components.", StringComparison.Ordinal) && name.EndsWith(".json", StringComparison.Ordinal)
                || name is "semantic-dom-catalog.json" or "llms-tokens.json"
                || file.Path.Replace('\\', '/').Contains("/docs/") && (name.EndsWith(".en-US.md", StringComparison.Ordinal) || name.EndsWith(".zh-CN.md", StringComparison.Ordinal));
        }).Select((file, token) => new Input(file.Path, file.GetText(token)?.ToString() ?? "")).Collect();
        context.RegisterSourceOutput(inputs, (output, files) => {
            try
            {
                using var semantics = JsonDocument.Parse(files.FirstOrDefault(f => Path.GetFileName(f.Path) == "semantic-dom-catalog.json")?.Text ?? "{}");
                var tokenInput = files.FirstOrDefault(f => Path.GetFileName(f.Path) == "llms-tokens.json");
                if (files.Any(f => Path.GetFileName(f.Path).StartsWith("components.", StringComparison.Ordinal)) && tokenInput == null)
                    throw new InvalidOperationException("Missing llms-tokens.json; run the docs CLI llms-tokens command before compiling.");
                using var tokens = JsonDocument.Parse(tokenInput?.Text ?? "{}");
                var docs = new List<(string Kind, string Language, string Name, string Markdown)>();
                foreach (var file in files.OrderBy(f => f.Path, StringComparer.Ordinal))
                {
                    var name = Path.GetFileName(file.Path);
                    if (name.StartsWith("components.", StringComparison.Ordinal))
                    {
                        var language = name.Substring("components.".Length).Replace(".json", "");
                        using var components = JsonDocument.Parse(file.Text);
                        foreach (var component in components.RootElement.EnumerateArray())
                        {
                            if (component.GetProperty("Category").GetString() != "Components") continue;
                            var title = component.GetProperty("Title").GetString()!;
                            docs.Add(("components", language, title, LlmsMarkdownBuilder.Build(component, language, semantics.RootElement, tokens.RootElement)));
                        }
                    }
                    else if (name.EndsWith(".md", StringComparison.Ordinal))
                    {
                        var language = name.EndsWith(".zh-CN.md", StringComparison.Ordinal) ? "zh-CN" : "en-US";
                        var key = name.Substring(0, name.Length - language.Length - 4);
                        var title = Regex.Match(file.Text, @"^title:\s*(.+)$", RegexOptions.Multiline).Groups[1].Value.Trim();
                        var body = Regex.Replace(file.Text.TrimStart('\uFEFF'), @"\A---\s*\r?\n.*?\r?\n---\s*\r?\n", "", RegexOptions.Singleline);
                        docs.Add(("docs", language, key, (body.StartsWith("# ", StringComparison.Ordinal) ? body : "# " + title + "\n\n" + body).Replace("\r\n", "\n")));
                    }
                }
                var code = new StringBuilder("// <auto-generated />\n#nullable enable\nnamespace AntDesign.Docs.Services;\ninternal static class GeneratedLlmsMarkdown\n{\n");
                // The existing demo catalog already approaches the CLR #US heap
                // limit. Pack prepared Markdown at compilation; decode/cache only,
                // never parse HTML or execute generation in the running site.
                code.AppendLine("    private static string Decode(string value) { using var input = new System.IO.MemoryStream(System.Convert.FromBase64String(value)); using var gzip = new System.IO.Compression.GZipStream(input, System.IO.Compression.CompressionMode.Decompress); using var reader = new System.IO.StreamReader(gzip, System.Text.Encoding.UTF8); return reader.ReadToEnd(); }");
                for (var i = 0; i < docs.Count; i++)
                    code.Append("    private static readonly System.Lazy<string> Document_").Append(i).Append(" = new(() => Decode(").Append(Literal(Pack(docs[i].Markdown))).AppendLine("));");
                code.AppendLine("    internal static string? Get(string kind, string name, string language) => (kind, name.ToLowerInvariant(), language) switch {");
                for (var i = 0; i < docs.Count; i++)
                    code.Append("        (").Append(Literal(docs[i].Kind)).Append(", ").Append(Literal(docs[i].Name.ToLowerInvariant())).Append(", ").Append(Literal(docs[i].Language)).Append(") => Document_").Append(i).AppendLine(".Value,");
                code.AppendLine("        _ => null,\n    };");
                code.AppendLine("    internal static string[] Names(string kind, string language) => (kind, language) switch {");
                foreach (var group in docs.GroupBy(d => (d.Kind, d.Language)))
                    code.Append("        (").Append(Literal(group.Key.Kind)).Append(", ").Append(Literal(group.Key.Language)).Append(") => new string[] { ").Append(string.Join(", ", group.Select(d => d.Name).OrderBy(n => n, StringComparer.Ordinal).Select(Literal))).AppendLine(" },");
                code.AppendLine("        _ => System.Array.Empty<string>(),\n    };\n}");
                output.AddSource("GeneratedLlmsMarkdown.g.cs", SourceText.From(code.ToString(), Encoding.UTF8));
            }
            catch (Exception error) { output.ReportDiagnostic(Diagnostic.Create(InvalidInput, Location.None, error.Message)); }
        });
    }
    private static string Literal(string text) => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(text, true);
    private static string Pack(string markdown)
    {
        using var output = new MemoryStream();
        using (var gzip = new GZipStream(output, CompressionLevel.Optimal, true))
        {
            var bytes = Encoding.UTF8.GetBytes(markdown);
            gzip.Write(bytes, 0, bytes.Length);
        }
        return Convert.ToBase64String(output.ToArray());
    }
    private sealed class Input
    {
        internal string Path { get; }
        internal string Text { get; }
        internal Input(string path, string text) { Path = path; Text = text; }
    }
}
