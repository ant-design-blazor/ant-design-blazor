using System;
using System.Linq;
using System.Text;
using System.Text.Json;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace AntDesign.Docs.Generator;

[Generator]
public sealed class SemanticDomCatalogGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor InvalidCatalog = new(
        "ADBSDOM001",
        "Invalid Semantic DOM catalog",
        "Could not generate SemanticDomCatalog from '{0}': {1}",
        "Semantic DOM",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var catalog = context.AdditionalTextsProvider
            .Where(static file => file.Path.EndsWith("semantic-dom-catalog.json", StringComparison.OrdinalIgnoreCase))
            .Select(static (file, cancellationToken) => (file.Path, Text: file.GetText(cancellationToken)?.ToString()));

        context.RegisterSourceOutput(catalog, static (productionContext, item) =>
        {
            if (string.IsNullOrWhiteSpace(item.Text))
            {
                productionContext.ReportDiagnostic(Diagnostic.Create(InvalidCatalog, Location.None, item.Path, "file is empty or unreadable"));
                return;
            }

            try
            {
                productionContext.AddSource("SemanticDomGeneratedCatalog.g.cs", SourceText.From(Generate(item.Text!), Encoding.UTF8));
            }
            catch (Exception exception)
            {
                productionContext.ReportDiagnostic(Diagnostic.Create(InvalidCatalog, Location.None, item.Path, exception.Message));
            }
        });
    }

    private static string Generate(string json)
    {
        using var document = JsonDocument.Parse(json);
        var components = document.RootElement.GetProperty("components").EnumerateArray()
            .Select(component => new
            {
                Name = component.GetProperty("name").GetString() ?? string.Empty,
                Nodes = component.GetProperty("nodes").EnumerateArray().Select(node => new
                {
                    Name = node.GetProperty("name").GetString() ?? string.Empty,
                    Selector = node.GetProperty("selector").GetString() ?? string.Empty,
                    Description = node.GetProperty("description").GetString() ?? string.Empty,
                    Version = node.TryGetProperty("version", out var version) ? version.GetString() : null,
                }).ToArray(),
            }).ToArray();

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />")
            .AppendLine("using System;")
            .AppendLine("using System.Collections.Generic;")
            .AppendLine("using System.Collections.ObjectModel;")
            .AppendLine()
            .AppendLine("namespace AntDesign.Docs.Services;")
            .AppendLine()
            .AppendLine("internal static class SemanticDomGeneratedCatalog")
            .AppendLine("{")
            .AppendLine("    internal static readonly IReadOnlyDictionary<string, IReadOnlyList<SemanticDomNode>> Nodes =")
            .AppendLine("        new ReadOnlyDictionary<string, IReadOnlyList<SemanticDomNode>>(new Dictionary<string, IReadOnlyList<SemanticDomNode>>(StringComparer.OrdinalIgnoreCase)")
            .AppendLine("        {");

        foreach (var component in components)
        {
            builder.Append("            [").Append(Literal(component.Name)).Append("] = ");
            if (component.Nodes.Length == 0)
            {
                builder.AppendLine("Array.Empty<SemanticDomNode>(),");
                continue;
            }

            builder.AppendLine("new SemanticDomNode[]")
                .AppendLine("            {");
            foreach (var node in component.Nodes)
            {
                builder.Append("                new SemanticDomNode(")
                    .Append(Literal(node.Name)).Append(", ")
                    .Append(Literal(node.Selector)).Append(", ")
                    .Append(Literal(node.Description)).Append(", ")
                    .Append(Literal(node.Version)).AppendLine("),");
            }
            builder.AppendLine("            },");
        }

        builder.AppendLine("        });")
            .AppendLine("}");
        return builder.ToString();
    }

    private static string Literal(string? value) => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value ?? string.Empty, quote: true);
}
