using System;
using System.Linq;
using System.Text;
using System.Text.Json;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace AntDesign.Docs.Generator;

[Generator]
public sealed class SemanticDomCatalogGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor InvalidCatalog = new(
        "ADBSDOM001",
        "Invalid Semantic DOM catalog",
        "Could not generate SemanticDomCatalog from '{0}': {1}",
        "Semantic DOM",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var catalogs = context.AdditionalTextsProvider
            .Where(static file => file.Path.EndsWith("semantic-dom-catalog.json", StringComparison.OrdinalIgnoreCase)
                || file.Path.EndsWith("semantic-md-catalog.json", StringComparison.OrdinalIgnoreCase))
            .Select(static (file, cancellationToken) => (file.Path, Text: file.GetText(cancellationToken)?.ToString()))
            .Collect();

        context.RegisterSourceOutput(catalogs, static (productionContext, items) =>
        {
            var semanticCatalog = items.FirstOrDefault(static item => item.Path.EndsWith("semantic-dom-catalog.json", StringComparison.OrdinalIgnoreCase));
            var markdownCatalog = items.FirstOrDefault(static item => item.Path.EndsWith("semantic-md-catalog.json", StringComparison.OrdinalIgnoreCase));
            if (string.IsNullOrWhiteSpace(semanticCatalog.Text))
            {
                productionContext.ReportDiagnostic(Diagnostic.Create(InvalidCatalog, Location.None, semanticCatalog.Path ?? "semantic-dom-catalog.json", "file is empty or unreadable"));
                return;
            }

            try
            {
                productionContext.AddSource("SemanticDomGeneratedCatalog.g.cs", SourceText.From(Generate(semanticCatalog.Text!, markdownCatalog.Text), Encoding.UTF8));
            }
            catch (Exception exception)
            {
                productionContext.ReportDiagnostic(Diagnostic.Create(InvalidCatalog, Location.None, semanticCatalog.Path ?? "semantic-dom-catalog.json", exception.Message));
            }
        });
    }

    private static string Generate(string json, string? markdownJson)
    {
        using var document = JsonDocument.Parse(json);
        var components = document.RootElement.GetProperty("components").EnumerateArray()
            .Select(component => new
            {
                Name = component.GetProperty("name").GetString() ?? string.Empty,
                Nodes = component.GetProperty("nodes").EnumerateArray().Select(node => new
                {
                    Name = node.GetProperty("name").GetString() ?? string.Empty,
                    Selector = node.GetProperty("selector").GetString() ?? string.Empty,
                    Description = node.GetProperty("description").GetString() ?? string.Empty,
                    Version = node.TryGetProperty("version", out var version) ? version.GetString() : null,
                }).ToArray(),
            }).ToArray();

        var englishDescriptions = new System.Collections.Generic.Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        if (!string.IsNullOrWhiteSpace(markdownJson))
        {
            using var markdown = JsonDocument.Parse(markdownJson);
            foreach (var page in markdown.RootElement.GetProperty("pages").EnumerateArray()
                         .Where(static page => string.Equals(page.GetProperty("locale").GetString(), "en-US", StringComparison.OrdinalIgnoreCase)))
            {
                var componentName = page.GetProperty("component").GetString() ?? string.Empty;
                foreach (var part in page.GetProperty("parts").EnumerateArray())
                {
                    var name = part.GetProperty("name").GetString() ?? string.Empty;
                    var description = part.GetProperty("description").GetString() ?? string.Empty;
                    if (!string.IsNullOrWhiteSpace(componentName) && !string.IsNullOrWhiteSpace(name) && !string.IsNullOrWhiteSpace(description))
                    {
                        englishDescriptions[$"{componentName}.{name}"] = description;
                    }
                }
            }
        }

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />")
            .AppendLine("using System;")
            .AppendLine("using System.Collections.Generic;")
            .AppendLine("using System.Collections.ObjectModel;")
            .AppendLine()
            .AppendLine("namespace AntDesign.Docs.Services;")
            .AppendLine()
            .AppendLine("internal static class SemanticDomGeneratedCatalog")
            .AppendLine("{")
            .AppendLine("    internal static readonly IReadOnlyDictionary<string, IReadOnlyList<SemanticDomNode>> Nodes =")
            .AppendLine("        new ReadOnlyDictionary<string, IReadOnlyList<SemanticDomNode>>(new Dictionary<string, IReadOnlyList<SemanticDomNode>>(StringComparer.OrdinalIgnoreCase)")
            .AppendLine("        {");

        builder.AppendLine("            // Component entries follow.");

        foreach (var component in components)
        {
            builder.Append("            [").Append(Literal(component.Name)).Append("] = ");
            if (component.Nodes.Length == 0)
            {
                builder.AppendLine("Array.Empty<SemanticDomNode>(),");
                continue;
            }

            builder.AppendLine("new SemanticDomNode[]")
                .AppendLine("            {");
            foreach (var node in component.Nodes)
            {
                builder.Append("                new SemanticDomNode(")
                    .Append(Literal(node.Name)).Append(", ")
                    .Append(Literal(node.Selector)).Append(", ")
                    .Append(Literal(node.Description)).Append(", ")
                    .Append(Literal(node.Version)).AppendLine("),");
            }
            builder.AppendLine("            },");
        }

        builder.AppendLine("        });")
            .AppendLine()
            .AppendLine("    internal static readonly IReadOnlyDictionary<string, string> EnglishDescriptions =")
            .AppendLine("        new ReadOnlyDictionary<string, string>(new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)")
            .AppendLine("        {");
        foreach (var description in englishDescriptions.OrderBy(static item => item.Key, StringComparer.OrdinalIgnoreCase))
        {
            builder.Append("            [").Append(Literal(description.Key)).Append("] = ")
                .Append(Literal(description.Value)).AppendLine(",");
        }

        builder.AppendLine("        });")
            .AppendLine("}");
        return builder.ToString();
    }

    private static string Literal(string? value) => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value ?? string.Empty, quote: true);
}
