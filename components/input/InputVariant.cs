namespace AntDesign
{
    /// <summary>
    /// Visual style of an input component.
    /// </summary>
    public enum InputVariant
    {
        /// <summary>Displays the standard border.</summary>
        Outlined,

        /// <summary>Displays a filled background.</summary>
        Filled,

        /// <summary>Displays no border.</summary>
        Borderless,

        /// <summary>Displays only the bottom border.</summary>
        Underlined
    }
}
