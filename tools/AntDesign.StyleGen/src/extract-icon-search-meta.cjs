#!/usr/bin/env node

const fs = require('node:fs');
const path = require('node:path');
const { createRequire } = require('node:module');

const [reactRoot, outputFile, mode] = process.argv.slice(2);

if (!reactRoot || !outputFile) {
    console.error('Usage: node extract-icon-search-meta.cjs <ant-design-root> <output.cs> [--check]');
    process.exit(2);
}

const reactRequire = createRequire(path.join(path.resolve(reactRoot), 'package.json'));
reactRequire('tsx/cjs');

const metaPath = path.join(
    path.resolve(reactRoot),
    '.dumi/theme/builtins/IconSearch/meta/index.ts',
);
const metadata = reactRequire(metaPath).default;
const entries = Object.entries(metadata)
    .map(([icon, info]) => [icon, [...new Set(info.tags.map((tag) => String(tag)))].sort()])
    .sort(([left], [right]) => left.localeCompare(right, 'en'));

const lines = [
    '// <auto-generated />',
    '// Generated from ant-design/.dumi/theme/builtins/IconSearch/meta.',
    'using System;',
    'using System.Collections.Generic;',
    'using System.Linq;',
    '',
    'namespace AntDesign.Docs.Services;',
    '',
    'public static class IconSearchMetadata',
    '{',
    '    private static readonly Dictionary<string, string[]> TagsByIcon = new(StringComparer.OrdinalIgnoreCase)',
    '    {',
];

for (const [icon, tags] of entries) {
    lines.push(`        [${JSON.stringify(icon)}] = new[] { ${tags.map(JSON.stringify).join(', ')} },`);
}

lines.push(
    '    };',
    '',
    '    public static bool Matches(string componentName, string query)',
    '    {',
    '        if (string.IsNullOrWhiteSpace(componentName) || string.IsNullOrWhiteSpace(query))',
    '        {',
    '            return false;',
    '        }',
    '',
    '        var iconName = componentName;',
    '        foreach (var suffix in new[] { "Outlined", "Filled", "TwoTone" })',
    '        {',
    '            if (iconName.EndsWith(suffix, StringComparison.OrdinalIgnoreCase))',
    '            {',
    '                iconName = iconName[..^suffix.Length];',
    '                break;',
    '            }',
    '        }',
    '',
    '        return TagsByIcon.TryGetValue(iconName, out var tags)',
    '            && tags.Any(tag => tag.Contains(query, StringComparison.OrdinalIgnoreCase));',
    '    }',
    '}',
    '',
);

const generated = lines.join('\n');
const destination = path.resolve(outputFile);

if (mode === '--check') {
    if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== generated) {
        console.error(`Generated icon metadata is stale: ${destination}`);
        process.exit(1);
    }
    console.log(`Icon metadata is current (${entries.length} React metadata entries).`);
} else {
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.writeFileSync(destination, generated);
    console.log(`Generated ${entries.length} React icon metadata entries at ${destination}`);
}
