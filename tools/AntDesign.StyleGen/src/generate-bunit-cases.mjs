#!/usr/bin/env node

import fs from 'node:fs';
import process from 'node:process';
import Ajv from 'ajv';
import { readReactSnapshot } from './html-structure-compare.mjs';

function loadCaseFile(path) {
  const value = JSON.parse(fs.readFileSync(path, 'utf8'));
  const schema = JSON.parse(fs.readFileSync(new URL('../schema/dom-case.schema.json', import.meta.url), 'utf8'));
  const validate = new Ajv({ allErrors: true }).compile(schema);
  if (!validate(value)) throw new Error(`Invalid DOM case file: ${JSON.stringify(validate.errors)}`);
  return value;
}

function escapeCSharp(value) {
  return value.replace(/"/g, '""');
}

function csharpValue(value, expression) {
  if (expression) return expression;
  if (value === null) return 'null';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'number') return String(value);
  return `"${escapeCSharp(value)}"`;
}

function generateAction(action) {
  if (action.type === 'click') return `cut.Find("${escapeCSharp(action.selector)}").Click();`;
  if (action.type === 'focus') return `cut.Find("${escapeCSharp(action.selector)}").Focus();`;
  if (action.type === 'blur') return `cut.Find("${escapeCSharp(action.selector)}").Blur();`;
  if (action.type === 'wait') return `cut.WaitForState(() => true, System.TimeSpan.FromMilliseconds(${action.milliseconds ?? 0}));`;
  if (action.type === 'change') return `cut.Find("${escapeCSharp(action.selector)}").Change(${csharpValue(action.value)});`;
  throw new Error(`Unsupported action type: ${action.type}`);
}

function generateAssertion(assertion, index) {
  const selector = assertion.selector ? `cut.Find("${escapeCSharp(assertion.selector)}")` : 'cut';
  const expected = csharpValue(assertion.expected, assertion.csharp);
  switch (assertion.type) {
    case 'markup': return `cut.MarkupMatches(@"${escapeCSharp(assertion.expected)}");`;
    case 'exists': return `Assert.NotNull(${selector});`;
    case 'not-exists': return `Assert.Empty(cut.FindAll("${escapeCSharp(assertion.selector)}"));`;
    case 'class': return `Assert.Contains(${expected}, ${selector}.ClassList);`;
    case 'attribute': return `Assert.Equal(${expected}, ${selector}.GetAttribute("${escapeCSharp(assertion.name)}"));`;
    case 'text': return `Assert.Equal(${expected}, ${selector}.TextContent.Trim());`;
    case 'count': return `Assert.Equal(${expected}, cut.FindAll("${escapeCSharp(assertion.selector)}").Count);`;
    case 'property': return `Assert.Equal(${expected}, cut.Instance.${assertion.property});`;
    default: throw new Error(`Unsupported assertion type at index ${index}: ${assertion.type}`);
  }
}

function generateCase(testCase) {
  const parameters = Object.entries(testCase.blazor.parameters ?? {})
    .filter(([name]) => name !== 'ChildContent')
    .map(([name, value]) => `parameters.Add(x => x.${name}, "${escapeCSharp(value)}");`)
    .join('\n            ');
  const childContent = testCase.blazor.childContent ?? testCase.blazor.parameters?.ChildContent;
  const child = childContent ? `parameters.AddChildContent("${escapeCSharp(childContent)}");` : '';
  const expected = readReactSnapshot(
    fs.readFileSync(testCase.react.snapshot, 'utf8'),
    testCase.react.key,
  );
  const steps = (testCase.steps ?? []).map((step) => {
    const changes = (step.changes ?? []).map((change) =>
      `cut.SetParametersAndRender(parameters => parameters.Add(x => x.${change.parameter}, ${csharpValue(change.value, change.csharp)}));`,
    );
    const actions = (step.actions ?? []).map(generateAction);
    const assertions = step.assertions.map(generateAssertion);
    return `\n        // Step: ${step.id}\n        ${[...changes, ...actions, ...assertions].join('\n        ')}`;
  }).join('');
  return `    [Fact]\n    public void React_${testCase.id}_matches_Blazor()\n    {\n        var cut = Context.RenderComponent<${testCase.blazor.type}>(parameters =>\n        {\n            ${parameters}\n            ${child}\n        });\n\n        cut.MarkupMatches(@"${escapeCSharp(expected)}");${steps}\n    }`;
}

export function generateBunitCases(caseFile) {
  const value = loadCaseFile(caseFile);
  return `// <auto-generated />\nusing Xunit;\n\nnamespace AntDesignV6.Tests;\n\npublic sealed class GeneratedReactDomCases : AntDesign.Tests.AntDesignTestBase\n{\n${value.cases.map(generateCase).join('\n\n')}\n}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const input = process.argv[2];
  if (!input) {
    console.error('Usage: node generate-bunit-cases.mjs <dom-cases.json>');
    process.exit(2);
  }
  process.stdout.write(generateBunitCases(input));
}
