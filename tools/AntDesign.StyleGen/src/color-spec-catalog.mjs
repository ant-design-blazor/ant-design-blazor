import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';

export async function syncColorSpec({ antdPath, output, check = false }) {
  const require = createRequire(join(resolve(antdPath), 'package.json'));
  const ts = require('typescript');
  const { presetPrimaryColors } = require('@ant-design/colors');
  function extract(source, variable) {
    const file = ts.createSourceFile('colors.tsx', source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
    function literal(node) {
      if (ts.isAsExpression(node)) return literal(node.expression);
      if (ts.isStringLiteral(node) || ts.isNumericLiteral(node)) return node.text;
      if (ts.isArrayLiteralExpression(node)) return node.elements.map(literal);
      if (ts.isObjectLiteralExpression(node)) return Object.fromEntries(node.properties.map(p => [p.name.getText(file).replace(/^['"]|['"]$/g, ''), literal(p.initializer)]));
      throw new Error(`Unsupported ${variable} literal: ${node.kind}`);
    }
    let value;
    function visit(node) {
      if (ts.isVariableDeclaration(node) && node.name.getText(file) === variable) value = literal(node.initializer);
      ts.forEachChild(node, visit);
    }
    visit(file);
    if (!value) throw new Error(`Missing React color metadata: ${variable}`);
    return value;
  }
  const root = join(antdPath, '.dumi/theme/common/Color');
  const palettes = await readFile(join(root, 'ColorPalettes.tsx'), 'utf8');
  const keys = extract(palettes, 'COLOR_KEYS');
  const locales = extract(palettes, 'locales');
  const gray = extract(await readFile(join(root, 'ColorStyle.tsx'), 'utf8'), 'gray');
  const paletteSource = await readFile(join(root, 'Palette.tsx'), 'utf8');
  const paletteFile = ts.createSourceFile('Palette.tsx', paletteSource, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  let neutralPreviewCount;
  function findCount(node) {
    if (ts.isBindingElement(node) && node.name.getText(paletteFile) === 'count' && node.initializer && ts.isNumericLiteral(node.initializer))
      neutralPreviewCount = Number(node.initializer.text);
    ts.forEachChild(node, findCount);
  }
  findCount(paletteFile);
  if (!Number.isInteger(neutralPreviewCount) || neutralPreviewCount < 1 || neutralPreviewCount > Object.keys(gray).length)
    throw new Error('Missing or invalid React Palette default count');
  const quote = JSON.stringify;
  const rows = keys.map(name => [name, presetPrimaryColors[name].toLowerCase(), locales.en[name+'Title'], locales.cn[name+'Title'], locales.en[name+'Description'], locales.cn[name+'Description']]);
  const source = `// <auto-generated /> From React ColorPalettes.tsx, ColorStyle.tsx, Palette.tsx and @ant-design/colors.\nnamespace AntDesign.Docs.Services;\npublic sealed record ColorSpecDefinition(string Name, string PrimaryColor, string TitleEn, string TitleZh, string DescriptionEn, string DescriptionZh);\npublic static class ColorSpecCatalog\n{\n    public static readonly ColorSpecDefinition[] Palettes = {\n${rows.map(row => '        new('+row.map(quote).join(', ')+'),').join('\n')}\n    };\n    public const int NeutralPreviewCount = ${neutralPreviewCount};\n    public static readonly string[] Neutral = { ${Object.values(gray).map(quote).join(', ')} };\n}\n`;
  if (check) {
    if (await readFile(output, 'utf8') !== source) throw new Error('Color specification catalog is stale');
  } else await writeFile(output, source);
  return { palettes: rows.length, swatches: rows.length * 10, neutral: Object.values(gray).length, neutralPreviewCount, output };
}
