#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

function escape(value) { return String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"'); }
function pascalCase(value) { return value.split('-').map((part) => part ? part[0].toUpperCase() + part.slice(1) : part).join(''); }
function methodName(value) { return value.replace(/[^a-zA-Z0-9_]/g, '_'); }
function sourceComments(item) {
  const source = item.react.sourceSnippet || '(React source is unavailable)';
  const lines = source.replace(/\*\//g, '* /').split('\n').map((line) => `    // ${line}`);
  return [`    // React snapshot key: ${item.react.key}`, `    // React source file: ${item.react.sourceFile || 'unknown'}`, ...lines].join('\n');
}

function generateSupportFile(catalog) {
  const scenarioCases = catalog.cases.filter((item) => item.status === 'scenario-adapted');
  const scenarioMethods = scenarioCases.map((item) => {
    const scenario = item.blazorScenario;
    const parameterLines = Object.entries(scenario.parameters ?? {})
      .map(([name, value]) => `parameters.Add(x => x.${name}, ${typeof value === 'string' && value.includes('.') ? value : `"${escape(value)}"`});`)
      .join(' ');
    const child = scenario.childContent == null ? '' : `parameters.AddChildContent("${escape(scenario.childContent)}");`;
    return `        if (scenarioId == "${escape(scenario.id)}") return context.RenderComponent<${pascalCase(item.component)}>(parameters => { ${parameterLines} ${child} });`;
  }).join('\n');
  return `// <auto-generated />
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text.Json;
using Bunit;
using AntDesign;

namespace AntDesignV6.Tests;

internal static class ReactDomRedBaselineSupport
{
    public static IReadOnlyDictionary<string, string> ExpectedMarkup { get; } = LoadExpectedMarkup();

    public static Type ResolveComponentType(string component)
    {
        var typeName = string.Concat(component.Split('-').Select(part => char.ToUpperInvariant(part[0]) + part[1..]));
        return typeof(Button).Assembly.GetType($"AntDesign.{typeName}")
            ?? throw new Xunit.Sdk.XunitException($"No Blazor component adapter registered for '{component}'.");
    }

    public static IRenderedFragment RenderScenario(TestContext context, string component, string scenarioId)
    {
${scenarioMethods}
        throw new Xunit.Sdk.XunitException($"No React scenario adapter registered for '{component}' / '{scenarioId}'.");
    }

    private static IReadOnlyDictionary<string, string> LoadExpectedMarkup()
    {
        var path = Path.Combine(AppContext.BaseDirectory, "react-dom-test-catalog.json");
        using var document = JsonDocument.Parse(File.ReadAllText(path));
        return document.RootElement.GetProperty("cases").EnumerateArray().ToDictionary(
            item => item.GetProperty("id").GetString()!,
            item => item.GetProperty("react").GetProperty("expectedMarkup").GetString()!);
    }
}
`;
}

function generateComponentFile(component, cases) {
  const className = `ReactDomRedBaseline_${pascalCase(component)}Tests`;
  const methods = cases.map((item) => `
${sourceComments(item)}
    [Fact]
    public void React_${methodName(item.id)}_matches_Blazor()
    {
        var cut = ReactDomRedBaselineSupport.RenderScenario(Context, "${escape(component)}", "${escape(item.blazorScenario.id ?? '')}");
        Assert.True(ReactDomRedBaselineSupport.ExpectedMarkup.TryGetValue("${escape(item.id)}", out var expectedMarkup), "Missing React markup for case ${escape(item.id)}");
        cut.MarkupMatches(expectedMarkup);
    }
`).join('');
  return `// <auto-generated />
using Bunit;
using Xunit;

namespace AntDesignV6.Tests;

public sealed class ${className} : AntDesign.Tests.AntDesignTestBase
{
${methods}
}
`;
}

export function generateRedBaselineTestFiles(catalog) {
  const grouped = new Map();
  for (const item of catalog.cases) {
    if (!grouped.has(item.component)) grouped.set(item.component, []);
    grouped.get(item.component).push(item);
  }
  const files = { 'ReactDomRedBaselineSupport.g.cs': generateSupportFile(catalog) };
  for (const [component, cases] of [...grouped.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    files[`ReactDomRedBaseline_${pascalCase(component)}Tests.g.cs`] = generateComponentFile(component, cases);
  }
  return files;
}

export function generateRedBaselineTests(catalogOrPath) {
  const catalog = typeof catalogOrPath === 'string' ? JSON.parse(fs.readFileSync(catalogOrPath, 'utf8')) : catalogOrPath;
  return generateRedBaselineTestFiles(catalog);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const input = process.argv[2];
  const outputDirectory = process.argv[3];
  if (!input || !outputDirectory) {
    console.error('Usage: node generate-red-baseline-tests.mjs <catalog.json> <output-directory>');
    process.exit(2);
  }
  const catalog = JSON.parse(fs.readFileSync(input, 'utf8'));
  fs.mkdirSync(outputDirectory, { recursive: true });
  for (const file of fs.readdirSync(outputDirectory)) {
    if (file.startsWith('ReactDomRedBaseline_') && file.endsWith('.g.cs')) fs.unlinkSync(path.join(outputDirectory, file));
  }
  const files = generateRedBaselineTestFiles(catalog);
  for (const [file, source] of Object.entries(files)) fs.writeFileSync(path.join(outputDirectory, file), source);
  console.log(JSON.stringify({ outputDirectory, files: Object.keys(files).length }, null, 2));
}
