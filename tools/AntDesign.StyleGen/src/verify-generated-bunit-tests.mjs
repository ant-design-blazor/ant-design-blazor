#!/usr/bin/env node

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const generatedHeader = '// <auto-generated />';

function sha256(value) {
  return crypto.createHash('sha256').update(value).digest('hex');
}

export function verifyGeneratedBunitTests(output) {
  const manifestPath = path.join(output, '.generated-manifest.json');
  if (!fs.existsSync(manifestPath)) throw new Error(`Generated manifest not found: ${manifestPath}`);
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  const failures = [];
  for (const [file, expectedHash] of Object.entries(manifest.files ?? {})) {
    const fullPath = path.join(output, file);
    if (!fs.existsSync(fullPath)) {
      failures.push(`${file}: missing`);
      continue;
    }
    const source = fs.readFileSync(fullPath, 'utf8');
    if (!source.startsWith(generatedHeader)) failures.push(`${file}: missing auto-generated header`);
    if (sha256(source) !== expectedHash) failures.push(`${file}: content hash mismatch`);
  }
  const generatedFiles = fs.readdirSync(output).filter((file) => file.endsWith('.g.cs'));
  const listedFiles = new Set(Object.keys(manifest.files ?? {}));
  for (const file of generatedFiles) if (!listedFiles.has(file)) failures.push(`${file}: not listed in manifest`);
  return { valid: failures.length === 0, files: listedFiles.size, failures, manifest };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const output = process.argv[2];
  if (!output) { console.error('Usage: node verify-generated-bunit-tests.mjs <output-directory>'); process.exit(2); }
  const result = verifyGeneratedBunitTests(path.resolve(output));
  console.log(JSON.stringify(result, null, 2));
  if (!result.valid) process.exitCode = 1;
}
